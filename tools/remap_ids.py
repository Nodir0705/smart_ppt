"""Remap positional element ids between two builds of a deck index.

Element ids (`s{slide}_e{n}`) are emission-order positions, so a parser change that adds,
drops or re-types one element shifts every later id on that slide. Hand-made artefacts
(slide maps, presenter scripts, presenter expected/adjudication files) must be remapped,
never regenerated.

    python3 -m tools.remap_ids OLD_INDEX NEW_INDEX --out map.json
    python3 -m tools.remap_ids OLD_INDEX NEW_INDEX --apply out/maps/<deck> out/bench/<deck>/presenter_script*.json out/bench/<deck>/presenter*

Matching, per slide: same normalised text (NFKC, casefold, alphanumerics) -> best bbox IoU;
text-less elements -> same type with IoU >= 0.5; the rest are dropped (-> null). New
elements nobody matched are listed as `new`.

Applying rewrites every `*.json` under the given paths in place: ids are replaced wherever
they occur (list entries, dict values, dict keys); a null-mapped id is removed from lists and
keys, nulled as a value. Slide maps additionally get `tools.local_slide_map.fixup` against a
packet from the new index (new ids become items + singleton units; emptied units go).
Packet-shaped files (`elements` + `png`) are skipped. Pass presenter dirs and script files,
not deck roots: the deck-root expected.json/narration.json are generated by deck_bench.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
import unicodedata
from pathlib import Path

ID = re.compile(r"^s\d+_e\d+$")
MIN_SIDE = 0.1   # inches: zero-area lines (connector arrows) still overlap themselves


def norm_text(t: str | None) -> str:
    return "".join(c for c in unicodedata.normalize("NFKC", t or "").casefold() if c.isalnum())


def _box(b: dict) -> tuple[float, float, float, float]:
    w, h = max(b["w"], MIN_SIDE), max(b["h"], MIN_SIDE)
    return b["x"], b["y"], b["x"] + w, b["y"] + h


def iou(a: dict, b: dict) -> float:
    ax0, ay0, ax1, ay1 = _box(a)
    bx0, by0, bx1, by1 = _box(b)
    iw, ih = min(ax1, bx1) - max(ax0, bx0), min(ay1, by1) - max(ay0, by0)
    if iw <= 0 or ih <= 0:
        return 0.0
    inter = iw * ih
    return inter / ((ax1 - ax0) * (ay1 - ay0) + (bx1 - bx0) * (by1 - by0) - inter)


def _centre_dist(a: dict, b: dict) -> float:
    return ((a["x"] + a["w"] / 2 - b["x"] - b["w"] / 2) ** 2
            + (a["y"] + a["h"] / 2 - b["y"] - b["h"] / 2) ** 2) ** 0.5


def match_slide(old: list[dict], new: list[dict]) -> dict[str, str | None]:
    """old id -> new id (None = dropped), greedy in old emission order."""
    free = list(range(len(new)))
    out: dict[str, str | None] = {}

    def take(o: dict, cands: list[int]) -> None:
        j = max(cands, key=lambda j: (iou(o["bbox"], new[j]["bbox"]),
                                      -_centre_dist(o["bbox"], new[j]["bbox"]), -j))
        out[o["id"]] = new[j]["id"]
        free.remove(j)

    for o in old:   # 1) same text
        t = norm_text(o.get("text"))
        if t:
            cands = [j for j in free if norm_text(new[j].get("text")) == t]
            out[o["id"]] = None
            if cands:
                take(o, cands)
    for o in old:   # 2) text-less (or symbol-only): same type, IoU >= .5
        if o["id"] in out:
            continue
        cands = [j for j in free if new[j]["type"] == o["type"] and iou(o["bbox"], new[j]["bbox"]) >= 0.5]
        out[o["id"]] = None
        if cands:
            take(o, cands)
    return {o["id"]: out[o["id"]] for o in old}


def build_id_map(old_index: dict, new_index: dict) -> dict:
    """{"deck", "map": {old: new|None}, "dropped": [old], "new": [new], "retyped": [...]}."""
    old_slides = {s["slide_number"]: s["elements"] for s in old_index["slides"]}
    new_slides = {s["slide_number"]: s["elements"] for s in new_index["slides"]}
    id_map: dict[str, str | None] = {}
    retyped = []
    for n in sorted(set(old_slides) | set(new_slides)):
        old, new = old_slides.get(n, []), new_slides.get(n, [])
        m = match_slide(old, new)
        id_map.update(m)
        types = {e["id"]: e["type"] for e in new}
        retyped += [{"old": o["id"], "new": m[o["id"]], "from": o["type"], "to": types[m[o["id"]]]}
                    for o in old if m[o["id"]] and types[m[o["id"]]] != o["type"]]
    matched = set(id_map.values())
    return {"deck": new_index.get("deck"), "map": id_map,
            "dropped": [k for k, v in id_map.items() if v is None],
            "new": [e["id"] for s in new_index["slides"] for e in s["elements"] if e["id"] not in matched],
            "retyped": retyped}


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("old_index", type=Path)
    ap.add_argument("new_index", type=Path)
    ap.add_argument("--out", type=Path, help="write the id map here")
    a = ap.parse_args(argv)
    result = build_id_map(json.loads(a.old_index.read_text()), json.loads(a.new_index.read_text()))
    text = json.dumps(result, indent=1, ensure_ascii=False) + "\n"
    if a.out:
        a.out.write_text(text)
    else:
        print(text, end="")
    return 0


if __name__ == "__main__":
    sys.exit(main())
